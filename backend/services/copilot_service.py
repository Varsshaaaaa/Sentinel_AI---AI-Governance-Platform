"""AI Policy Copilot — natural language to policy YAML."""

import logging
import re

from governance.policy_engine.loader import PolicyLoader

logger = logging.getLogger(__name__)


COPILOT_TEMPLATES = {
    "bulk_delete_block": """apiVersion: sentinelai.io/v1
kind: Policy
metadata:
  name: {name}
  description: Generated by Policy Copilot
spec:
  inherits: base-enterprise-policy
  rules:
    - name: bulk-delete-block
      priority: 200
      when:
        all:
          - context.action_type: delete
          - context.data_scope_size >: {limit}
      then:
        action: block
        reason: "Bulk delete exceeds limit of {limit} records"
""",
    "after_hours_hitl": """apiVersion: sentinelai.io/v1
kind: Policy
metadata:
  name: {name}
  description: Generated by Policy Copilot
spec:
  inherits: base-enterprise-policy
  rules:
    - name: after-hours-write-hitl
      priority: 100
      when:
        all:
          - context.timestamp.hour outside: [9, 18]
          - context.action_type in: [write, delete]
      then:
        action: require_hitl
        reason: "Data modification outside business hours requires approval"
""",
    "external_email_hitl": """apiVersion: sentinelai.io/v1
kind: Policy
metadata:
  name: {name}
  description: Generated by Policy Copilot
spec:
  rules:
    - name: external-email-hitl
      priority: 150
      when:
        all:
          - context.tool_name: email_send
          - context.tool_params.to_domain external: [company.com, internal.local]
      then:
        action: require_hitl
        reason: "External email requires human approval"
""",
    "violation_suspend": """apiVersion: sentinelai.io/v1
kind: Policy
metadata:
  name: {name}
  description: Generated by Policy Copilot
spec:
  rules:
    - name: violation-suspend
      priority: 400
      when:
        - context.previous_violations_in_session >=: 3
      then:
        action: suspend_session
        reason: "Session suspended after repeated violations"
""",
}


class PolicyCopilot:
    """Generates policy YAML from natural language descriptions."""

    def generate(self, description: str, policy_name: str = "copilot-policy") -> dict:
        from shared.config.settings import get_settings

        settings = get_settings()
        description_lower = description.lower()
        yaml_content = None
        if not settings.copilot_skip_templates:
            yaml_content = self._match_template(description_lower, policy_name)

        if not yaml_content:
            yaml_content = self._generate_via_llm(description, policy_name)

        try:
            policy = PolicyLoader.parse_yaml(yaml_content)
            valid = True
            error = None
        except Exception as exc:
            valid = False
            error = str(exc)
            policy = None

        return {
            "yaml_content": yaml_content,
            "policy_name": policy_name,
            "valid": valid,
            "error": error,
            "parsed_policy": policy.model_dump() if policy else None,
            "requires_human_approval": True,
        }

    def _match_template(self, description: str, name: str) -> str | None:
        limit_match = re.search(r"(\d+)\s*record", description)
        limit = limit_match.group(1) if limit_match else "100"

        if any(k in description for k in ("delet", "bulk", "remove")) and (
            "100" in description or "bulk" in description or limit_match
        ):
            if any(k in description for k in ("hour", "business", "6 pm", "6pm", "after")):
                return f"""apiVersion: sentinelai.io/v1
kind: Policy
metadata:
  name: {name}
  description: Generated by Policy Copilot
spec:
  inherits: base-enterprise-policy
  rules:
    - name: bulk-delete-block
      priority: 200
      when:
        all:
          - context.action_type: delete
          - context.data_scope_size >: {limit}
      then:
        action: block
        reason: "Bulk delete exceeds limit of {limit} records"
    - name: after-hours-write-hitl
      priority: 100
      when:
        all:
          - context.timestamp.hour outside: [9, 18]
          - context.action_type in: [write, delete]
      then:
        action: require_hitl
        reason: "Data modification outside business hours requires approval"
"""
            return COPILOT_TEMPLATES["bulk_delete_block"].format(name=name, limit=limit)

        if ("after" in description or "business hour" in description or "6 pm" in description or "6pm" in description):
            if "delete" in description or "write" in description or "modif" in description:
                return COPILOT_TEMPLATES["after_hours_hitl"].format(name=name)

        if "email" in description and ("external" in description or "outside" in description):
            return COPILOT_TEMPLATES["external_email_hitl"].format(name=name)

        if "violation" in description and ("suspend" in description or "three" in description or "3" in description):
            return COPILOT_TEMPLATES["violation_suspend"].format(name=name)

        if "finance" in description and any(k in description for k in ("delet", "bulk", "remove")):
            return COPILOT_TEMPLATES["bulk_delete_block"].format(name=name, limit=limit)

        return None

    def _generate_via_llm(self, description: str, name: str) -> str:
        try:
            from shared.config.settings import get_settings
            from shared.llm.client import completion, extract_message_content, llm_configured

            if not llm_configured():
                return self._fallback_yaml(name, description)

            prompt = f"""Generate a SentinelAI governance policy in YAML format for this requirement:
"{description}"

Use this schema:
apiVersion: sentinelai.io/v1
kind: Policy
metadata:
  name: {name}
spec:
  inherits: base-enterprise-policy
  rules:
    - name: rule-name
      priority: 100
      when:
        all:
          - context.field: value
      then:
        action: block|require_hitl|allow|audit_only|suspend_session
        reason: "explanation"

Return ONLY valid YAML."""

            response = completion(
                messages=[{"role": "user", "content": prompt}],
                max_tokens=get_settings().copilot_max_tokens,
                temperature=0.2,
            )
            content = extract_message_content(response)
            if "```" in content:
                parts = content.split("```")
                for part in parts:
                    chunk = part.strip()
                    if chunk.startswith("yaml"):
                        chunk = chunk[4:].strip()
                    if chunk.startswith("apiVersion:"):
                        content = chunk
                        break
            return content.strip()
        except Exception as exc:
            logger.warning("Policy Copilot LLM generation failed: %s", exc)
            return self._fallback_yaml(name, description)

    def _fallback_yaml(self, name: str, description: str) -> str:
        return f"""apiVersion: sentinelai.io/v1
kind: Policy
metadata:
  name: {name}
  description: "{description[:200]}"
spec:
  inherits: base-enterprise-policy
  rules:
    - name: copilot-generated-rule
      priority: 100
      when:
        all:
          - context.action_type in: [write, delete]
      then:
        action: require_hitl
        reason: "Generated policy requires human review"
"""
